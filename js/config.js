const VERSAO_PRODUTOS_COMPLEMENTARES = 7;

window.aplicarProdutosComplementares = function (catalogo) {
  if (Number(catalogo.versaoProdutosComplementares) >= VERSAO_PRODUTOS_COMPLEMENTARES) return catalogo;
  const resultado = {
    ...catalogo,
    categorias: [...(Array.isArray(catalogo.categorias) ? catalogo.categorias : [])],
    produtos: [...(Array.isArray(catalogo.produtos) ? catalogo.produtos : [])]
  };
  const produtosNovos = window.LOJA_PADRAO.produtos.filter((produto) => (
    produto.categoria === "Óculos inteligentes"
    || produto.id === "travesseiro-derila-ergo"
  ));
  produtosNovos.forEach((produtoNovo) => {
    if (!resultado.categorias.includes(produtoNovo.categoria)) {
      resultado.categorias.push(produtoNovo.categoria);
    }
    const produtoExistente = resultado.produtos.find((produto) => String(produto.id) === String(produtoNovo.id));
    if (!produtoExistente) {
      resultado.produtos.push(structuredClone(produtoNovo));
      return;
    }

    if (typeof produtoExistente.descricao === "string") {
      produtoExistente.descricao = produtoExistente.descricao.replace(" A imagem é ilustrativa.", ".");
    }

    const atualizarImagemIlustrativa =
      produtoExistente.imagem === "imagens/produtos/oculos-inteligentes.svg"
      && produtoNovo.imagem !== "imagens/produtos/oculos-inteligentes.svg";
    if (atualizarImagemIlustrativa) {
      produtoExistente.imagem = produtoNovo.imagem;
      produtoExistente.imagens = Array.isArray(produtoNovo.imagens) ? [...produtoNovo.imagens] : [];
      produtoExistente.descricao = produtoNovo.descricao;
    }

    if (produtoNovo.id !== "rayban-meta-wayfarer-gen2-rw4012-601-1m-53") return;
    if (atualizarImagemIlustrativa) {
      if (produtoExistente.paginaOrigem === "https://www.oticasdiniz.com.br/oculos/oculos-inteligentes") {
        produtoExistente.paginaOrigem = produtoNovo.paginaOrigem;
      }
      if (
        produtoExistente.preco === 3633.51
        && produtoExistente.precoPromocional === 3633.51
        && produtoExistente.precoPix === null
        && produtoExistente.antigo === 4128.99
      ) {
        produtoExistente.preco = produtoNovo.precoPix;
        produtoExistente.precoPromocional = produtoNovo.precoPromocional;
        produtoExistente.precoPix = produtoNovo.precoPix;
      }
    }
  });
  resultado.versaoProdutosComplementares = VERSAO_PRODUTOS_COMPLEMENTARES;
  return resultado;
};

function aplicarIdentidadePC(catalogo) {
  let alterado = false;
  const nomesAntigos = ["Mineiro Net UAI", "Mineiro Cards UAI"];
  const razoesAntigas = ["PROVEDOR DE INTERNET MINEIRO NET UAI LTDA", "MINEIRO NET UAI LTDA"];

  if (catalogo.loja.whatsapp !== window.LOJA_PADRAO.loja.whatsapp) {
    catalogo.loja.whatsapp = window.LOJA_PADRAO.loja.whatsapp;
    alterado = true;
  }
  if (catalogo.loja.telefone !== window.LOJA_PADRAO.loja.telefone) {
    catalogo.loja.telefone = window.LOJA_PADRAO.loja.telefone;
    alterado = true;
  }
  if (nomesAntigos.includes(catalogo.loja.nome)) {
    catalogo.loja.nome = window.LOJA_PADRAO.loja.nome;
    alterado = true;
  }
  if (razoesAntigas.includes(catalogo.loja.razaoSocial)) {
    catalogo.loja.razaoSocial = window.LOJA_PADRAO.loja.razaoSocial;
    alterado = true;
  }
  if (!catalogo.loja.cnpj) {
    catalogo.loja.cnpj = window.LOJA_PADRAO.loja.cnpj;
    alterado = true;
  }
  if (catalogo.loja.endereco === "Minas Gerais, Brasil") {
    catalogo.loja.endereco = window.LOJA_PADRAO.loja.endereco;
    alterado = true;
  }
  if (["imagens/logo.svg", "imagens/logo-pc-almofadas.svg"].includes(catalogo.loja.logo)) {
    catalogo.loja.logo = window.LOJA_PADRAO.loja.logo;
    alterado = true;
  }
  if (["imagens/logo.svg", "imagens/logo-pc-almofadas.svg"].includes(catalogo.loja.favicon)) {
    catalogo.loja.favicon = window.LOJA_PADRAO.loja.favicon;
    alterado = true;
  }
  if (["MINEIRO NET UAI LTDA", "MINEIRO CARDS UAI"].includes(catalogo.pix.nomeRecebedor)) {
    catalogo.pix.nomeRecebedor = window.LOJA_PADRAO.pix.nomeRecebedor;
    alterado = true;
  }
  if (catalogo.pix.cidade === "BELO HORIZONTE") {
    catalogo.pix.cidade = window.LOJA_PADRAO.pix.cidade;
    alterado = true;
  }
  if (catalogo.pix.mensagem === "Pedido Mineiro Cards UAI") {
    catalogo.pix.mensagem = window.LOJA_PADRAO.pix.mensagem;
    alterado = true;
  }

  return alterado;
}

window.carregarLojaConfigurada = function () {
  const chave = "mineironet_loja";
  const salvo = localStorage.getItem(chave);
  if (!salvo) return structuredClone(window.LOJA_PADRAO);

  let dadosSalvos;
  try {
    dadosSalvos = JSON.parse(salvo);
  } catch {
    return structuredClone(window.LOJA_PADRAO);
  }

  const loja = {
    ...structuredClone(window.LOJA_PADRAO),
    ...dadosSalvos,
    loja: { ...window.LOJA_PADRAO.loja, ...dadosSalvos.loja },
    pix: { ...window.LOJA_PADRAO.pix, ...dadosSalvos.pix },
    pagamento: {
      ...window.LOJA_PADRAO.pagamento,
      ...dadosSalvos.pagamento,
      gateway: {
        ...window.LOJA_PADRAO.pagamento.gateway,
        ...((dadosSalvos.pagamento && dadosSalvos.pagamento.gateway) || {})
      }
    }
  };

  if (loja.pix.chave === "00000000000000") {
    loja.pix.chave = "";
    localStorage.setItem(chave, JSON.stringify(loja));
  }

  let identidadeAtualizada = aplicarIdentidadePC(loja);
  if (
    loja.loja.slogan === "Tecnologia, estilo e colecionáveis para o seu dia."
    || loja.loja.slogan === "Seu próximo deck Pokémon começa aqui!"
    || loja.loja.slogan === "Internet rápida pra sua casa, uai!"
  ) {
    loja.loja.slogan = window.LOJA_PADRAO.loja.slogan;
    identidadeAtualizada = true;
  }
  if (
    loja.loja.banner === "imagens/banner.svg"
    || (
      typeof loja.loja.banner === "string"
      && loja.loja.banner.startsWith("https://images2.ray-ban.com/")
    )
  ) {
    loja.loja.banner = window.LOJA_PADRAO.loja.banner;
    identidadeAtualizada = true;
  }
  if (identidadeAtualizada) localStorage.setItem(chave, JSON.stringify(loja));

  if (dadosSalvos.versaoCatalogo !== window.LOJA_PADRAO.versaoCatalogo) {
    loja.categorias = [...window.LOJA_PADRAO.categorias];
    loja.produtos = structuredClone(window.LOJA_PADRAO.produtos);
    loja.versaoCatalogo = window.LOJA_PADRAO.versaoCatalogo;
    localStorage.setItem(chave, JSON.stringify(loja));
  }

  const estavaAtualizada = Number(loja.versaoProdutosComplementares) >= VERSAO_PRODUTOS_COMPLEMENTARES;
  const lojaAtualizada = window.aplicarProdutosComplementares(loja);
  if (!estavaAtualizada) localStorage.setItem(chave, JSON.stringify(lojaAtualizada));
  return lojaAtualizada;
};

const STORAGE_PRODUTOS_RECENTES = "mineironet_produtos_recentes";

window.registrarProdutoVisitado = function (id) {
  if (id === undefined || id === null || String(id).trim() === "") return;
  try {
    const salvo = JSON.parse(localStorage.getItem(STORAGE_PRODUTOS_RECENTES) || "[]");
    const ids = Array.isArray(salvo) ? salvo.filter((produtoId) => typeof produtoId === "string") : [];
    const produtoId = String(id);
    localStorage.setItem(
      STORAGE_PRODUTOS_RECENTES,
      JSON.stringify([produtoId, ...ids.filter((item) => item !== produtoId)].slice(0, 8))
    );
  } catch (erro) {
    console.error("Não foi possível salvar o histórico de produtos visitados.", erro);
  }
};

window.listarProdutosRecentes = function (produtos, limite = 4) {
  try {
    const salvo = JSON.parse(localStorage.getItem(STORAGE_PRODUTOS_RECENTES) || "[]");
    if (!Array.isArray(salvo)) return [];
    const produtosPorId = new Map(produtos.map((produto) => [String(produto.id), produto]));
    return salvo
      .filter((id, indice) => typeof id === "string" && salvo.indexOf(id) === indice)
      .map((id) => produtosPorId.get(id))
      .filter(Boolean)
      .slice(0, limite);
  } catch (erro) {
    console.error("Não foi possível carregar o histórico de produtos visitados.", erro);
    return [];
  }
};

window.carregarLojaRemota = async function () {
  const local = window.carregarLojaConfigurada();
  if (window.location.protocol === "file:") return local;
  try {
    const response = await fetch("/api/store", { cache: "no-store" });
    if (response.status === 404) return local;
    if (!response.ok) throw new Error(`O servidor respondeu ${response.status}.`);
    const dados = await response.json();
    const catalogoComServidor = {
      ...local,
      ...dados,
      versaoProdutosComplementares: Number(dados.versaoProdutosComplementares) || 0,
      loja: { ...window.LOJA_PADRAO.loja, ...dados.loja },
      pix: { ...window.LOJA_PADRAO.pix, ...dados.pix },
      pagamento: {
        ...window.LOJA_PADRAO.pagamento,
        ...dados.pagamento,
        gateway: {
          ...window.LOJA_PADRAO.pagamento.gateway,
          ...((dados.pagamento && dados.pagamento.gateway) || {})
        }
      }
    };
    aplicarIdentidadePC(catalogoComServidor);
    if (
      catalogoComServidor.loja.slogan === "Seu próximo deck Pokémon começa aqui!"
      || catalogoComServidor.loja.slogan === "Internet rápida pra sua casa, uai!"
    ) {
      catalogoComServidor.loja.slogan = window.LOJA_PADRAO.loja.slogan;
    }
    if (catalogoComServidor.loja.banner === "imagens/banner.svg") {
      catalogoComServidor.loja.banner = window.LOJA_PADRAO.loja.banner;
    }
    return window.aplicarProdutosComplementares(catalogoComServidor);
  } catch (erro) {
    console.error("Não foi possível carregar a configuração compartilhada da loja.", erro);
    return local;
  }
};
